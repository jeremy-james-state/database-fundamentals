#!/usr/bin/env node
/**
 * Build a client-side search index from navigable MDX pages.
 *
 * Usage (from repo root):
 *   node scripts/build-search-index.mjs
 *
 * Writes:
 *   search-index.json          — static JSON (optional fetch / inspection)
 *   snippets/search-data.jsx   — imported by /search.mdx
 *
 * Re-run after adding or renaming pages, or changing title / description / keywords.
 * Mintlify's ⌘K bar is separate; this index powers the Local search page only.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const DOCS_JSON = path.join(ROOT, "docs.json");
const OUT_JSON = path.join(ROOT, "search-index.json");
const OUT_JS = path.join(ROOT, "snippets", "search-data.jsx");

function collectPages(nodes, out = [], skipHidden = false) {
  for (const node of nodes ?? []) {
    if (typeof node === "string") {
      if (!skipHidden) out.push(node);
      continue;
    }
    const hidden = node.hidden === true;
    if (Array.isArray(node.pages)) {
      collectPages(node.pages, out, skipHidden || hidden);
    }
  }
  return out;
}

function parseFrontmatter(raw) {
  const match = raw.match(/^---\r?\n([\s\S]*?)\r?\n---/);
  if (!match) return { data: {}, body: raw };
  const block = match[1];
  const data = {};
  const lines = block.split(/\r?\n/);
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    const kv = line.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!kv) {
      i += 1;
      continue;
    }
    const key = kv[1];
    let value = kv[2].trim();
    if (value === "" || value === "|" || value === ">") {
      i += 1;
      continue;
    }
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      data[key] = value.slice(1, -1);
      i += 1;
      continue;
    }
    if (value.startsWith("[")) {
      let buf = value;
      while (!buf.includes("]") && i + 1 < lines.length) {
        i += 1;
        buf += " " + lines[i].trim();
      }
      const inner = buf.replace(/^\[/, "").replace(/\]$/, "");
      data[key] = inner
        .split(",")
        .map((part) => part.trim().replace(/^["']|["']$/g, ""))
        .filter(Boolean);
      i += 1;
      continue;
    }
    if (value === "true" || value === "false") {
      data[key] = value === "true";
      i += 1;
      continue;
    }
    if (/^-?\d+(\.\d+)?$/.test(value)) {
      data[key] = Number(value);
      i += 1;
      continue;
    }
    data[key] = value;
    i += 1;
  }
  return { data, body: raw.slice(match[0].length) };
}

function extractHeadings(body, limit = 8) {
  const headings = [];
  for (const line of body.split(/\r?\n/)) {
    const m = line.match(/^##\s+(.+?)\s*$/);
    if (!m) continue;
    const text = m[1]
      .replace(/`([^`]+)`/g, "$1")
      .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
      .trim();
    if (text) headings.push(text);
    if (headings.length >= limit) break;
  }
  return headings;
}

function hrefFor(slug) {
  if (slug === "index") return "/";
  return `/${slug}`;
}

function resolveMdx(slug) {
  const candidates = [
    path.join(ROOT, `${slug}.mdx`),
    path.join(ROOT, slug, "index.mdx"),
  ];
  return candidates.find((p) => fs.existsSync(p)) ?? null;
}

function main() {
  const docs = JSON.parse(fs.readFileSync(DOCS_JSON, "utf8"));
  const slugs = collectPages(docs.navigation?.pages ?? []);
  const entries = [];
  const missing = [];

  for (const slug of slugs) {
    if (slug === "search") continue;
    const file = resolveMdx(slug);
    if (!file) {
      missing.push(slug);
      continue;
    }
    const raw = fs.readFileSync(file, "utf8");
    const { data, body } = parseFrontmatter(raw);
    if (data.hidden === true || data.noindex === true || data.searchable === false) {
      continue;
    }
    const title = typeof data.title === "string" ? data.title : slug;
    const description = typeof data.description === "string" ? data.description : "";
    const keywords = Array.isArray(data.keywords)
      ? data.keywords.map(String)
      : typeof data.keywords === "string"
        ? [data.keywords]
        : [];
    const headings = extractHeadings(body);
    entries.push({
      href: hrefFor(slug),
      title,
      description,
      keywords,
      headings,
      text: [title, description, ...keywords, ...headings].join(" ").toLowerCase(),
    });
  }

  entries.sort((a, b) => a.title.localeCompare(b.title));

  fs.mkdirSync(path.dirname(OUT_JS), { recursive: true });
  fs.writeFileSync(OUT_JSON, `${JSON.stringify({ generatedAt: new Date().toISOString(), pages: entries }, null, 2)}\n`);
  fs.writeFileSync(
    OUT_JS,
    `/* Generated by scripts/build-search-index.mjs — do not edit by hand. */\nexport const SEARCH_INDEX = ${JSON.stringify(entries, null, 2)};\n`
  );

  console.log(`Indexed ${entries.length} pages → search-index.json, snippets/search-data.jsx`);
  if (missing.length) {
    console.warn(`Missing MDX for ${missing.length} nav entries:\n  ${missing.join("\n  ")}`);
    process.exitCode = 1;
  }
}

main();
